#!/usr/bin/env python3
"""Regenerate source/streamlitd/assetlist.d: the list of files under assets/ that are
embedded into every streamlitd binary (D's import() cannot list directories).

Swagger UI (assets/vendor/swagger-ui/) gets its own list, `swaggerAssetNames`: it is embedded only
when the OpenAPI docs are compiled in (no `StreamlitdNoApiDocs` version)."""
import os
root = os.path.join(os.path.dirname(__file__), "..")
assets = os.path.join(root, "assets")
names, swagger = [], []
for d, _, files in os.walk(assets):
    for f in files:
        if f in ("LICENSE", "NOTICE") or f.endswith((".map", ".md")):
            continue
        rel = os.path.relpath(os.path.join(d, f), assets).replace(os.sep, "/")
        (swagger if rel.startswith("vendor/swagger-ui/") else names).append(rel)
names.sort()
swagger.sort()
with open(os.path.join(root, "source", "streamlitd", "assetlist.d"), "w") as out:
    out.write("/// Generated by tools/gen_assets.py — files embedded from assets/.\n")
    out.write("module streamlitd.assetlist;\n\n")
    out.write("/// Embedded asset paths (relative to assets/).\n")
    out.write("enum assetNames = [\n")
    for n in names:
        out.write('\t"%s",\n' % n)
    out.write("];\n\n")
    out.write("/// Swagger UI files, embedded only with the OpenAPI docs (see streamlitd.openapi).\n")
    out.write("enum swaggerAssetNames = [\n")
    for n in swagger:
        out.write('\t"%s",\n' % n)
    out.write("];\n")
print("%d assets, %d swagger assets" % (len(names), len(swagger)))
