#!/usr/bin/env python3
"""Generate docs/api-reference.md from the D sources: public declarations with their
`///` doc comments, grouped by area. Run after changing the public API."""
import os, re

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "source", "streamlitd")

# (title, file, intro, scope filter)
SECTIONS = [
    ("Text & status elements", "elements.d", "Methods on `St` for text, alerts, metrics and progress.", None),
    ("Input widgets", "widgets.d", "Widgets return their current value. Pass `key:` to bind the value to `st.session[key]`.", None),
    ("Layout containers", "layout.d", "Containers return a new `St` that writes into them (use `with (c) { ... }`).", None),
    ("Partial reruns: fragments, dialogs, status", "fragments.d", "", None),
    ("Data display", "dataelements.d", "", None),
    ("Charts & maps", "charts.d", "", "mixin"),
    ("Media, files & downloads", "mediaelements.d", "", "mixin"),
    ("Navigation (multipage)", "pages.d", "", None),
    ("Custom components", "components.d", "", None),
    ("App control, page config, themes, auth (`St` core)", "delta.d", "", None),
    ("Session state (`st.session`)", "state.d", "", None),
    ("DataFrame", "dataframe.d", "", None),
    ("Caching", "cache.d", "", None),
    ("Secrets", "secrets.d", "", None),
    ("Themes", "theme.d", "", None),
    ("Server & configuration", "config.d", "", None),
    ("Server, app routes & JSON API endpoints", "server.d", "See [JSON API endpoints](api-endpoints.md).", None),
    ("OpenAPI & Swagger UI", "openapi.d", "See [OpenAPI and Swagger UI](api-endpoints.md#openapi-and-swagger-ui).", None),
    ("Testing (`AppTest`)", "testing.d", "", None),
]

SIG_START = re.compile(r"^\t*(?:@property\s+)?(?:static\s+)?(?:[A-Za-z_][\w!\[\]\(\)\.]*(?:\[\d*\])?\s+)+[A-Za-z_]\w*(?:\([^)]*\))?\(")
SKIP_WORDS = ("private", "package", "unittest", "return ", "if (", "foreach", "while", "else", "auto ", "import ",
              "throw ", "case ", "switch", "enforce", "assert", "static foreach", "static if", "version")

def declarations(path, scope=None):
    lines = open(path, encoding="utf-8").read().split("\n")
    out = []
    doc = []
    in_mixin = False
    depth_type = []
    i = 0
    while i < len(lines):
        raw = lines[i]
        s = raw.strip()
        if s.startswith("mixin template"):
            in_mixin = True
            doc = []
            i += 1
            continue
        if s.startswith("///"):
            doc.append(s[3:].strip())
            i += 1
            continue
        if s.startswith("unittest") or s.startswith("version (unittest)"):
            # skip block
            depth = 0
            started = False
            while i < len(lines):
                depth += lines[i].count("{") - lines[i].count("}")
                if "{" in lines[i]:
                    started = True
                i += 1
                if started and depth <= 0:
                    break
            doc = []
            continue
        indent = len(raw) - len(raw.lstrip("\t"))
        is_type = re.match(r"^(final\s+)?(class|struct|enum|template|alias)\s", s)
        if doc and is_type and indent <= 1:
            name = s.split("{")[0].split("=")[0].strip()
            out.append(("type", name, " ".join(doc)))
            doc = []
            i += 1
            continue
        if doc and indent <= 2 and not any(s.startswith(w) for w in SKIP_WORDS) and "(" in s and not s.startswith("//"):
            sig = s
            j = i
            while sig.count("(") > sig.count(")") and j + 1 < len(lines):
                j += 1
                sig += " " + lines[j].strip()
            sig = sig.split("{")[0].strip()
            sig = re.sub(r"\s+if \(.*$", "", sig)
            sig = re.sub(r"\s+", " ", sig).rstrip(";")
            if scope != "mixin" or in_mixin:
                out.append(("fn", sig, " ".join(doc)))
            doc = []
            i = j + 1
            continue
        if s and not s.startswith("//"):
            doc = []
        i += 1
    return out

def main():
    md = ["# API reference", "",
          "_Generated by `tools/gen_api_docs.py` from the source doc comments — do not edit by hand._", "",
          "All element and widget methods are called on `St` (the `st` passed to your app function) or on a",
          "container returned by it (`st.sidebar`, `st.columns(2)[0]`, `st.expander(\"...\")`, ...).",
          "Optional parameters are usually passed by name: `st.slider(\"x\", 0, 10, 5, step: 2, key: \"s\")`.", "",
          "## Contents", ""]
    for title, f, _, _ in SECTIONS:
        anchor = re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")
        md.append(f"- [{title}](#{anchor})")
    md.append("")
    for title, f, intro, scope in SECTIONS:
        md.append(f"## {title}")
        md.append("")
        md.append(f"Source: [`source/streamlitd/{f}`](../source/streamlitd/{f})")
        md.append("")
        if intro:
            md.append(intro)
            md.append("")
        for kind, sig, doc in declarations(os.path.join(SRC, f), scope):
            if kind == "type":
                md.append(f"#### `{sig}`")
            else:
                md.append("```d")
                md.append(sig)
                md.append("```")
            if doc:
                md.append(doc.replace("---", "").strip())
            md.append("")
    open(os.path.join(ROOT, "docs", "api-reference.md"), "w", encoding="utf-8").write("\n".join(md))
    print("docs/api-reference.md written")

if __name__ == "__main__":
    main()
